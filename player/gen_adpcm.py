"""Generate the player's ADPCM decode loops and step tables (4, 3 and 2 bits).

run_player.build() calls write(build_dir): it writes adpcm_dec.inc (included
by player.asm) and ima{4,3,2}.bin.

Each table has a word per (step index, code): the signed difference << 13
and the next index's row offset (a row is 2^bits words), so one LDR does the
step lookup, the adds, the sign and the index update. The loops are unrolled
over one group of codes that fills whole words (4-bit: 8 codes in 1 word;
2-bit: 16 in 1; 3-bit: 32 in 3, two of them straddling a word boundary).
"""
import os
import struct

import adpcm_encode as ae

GROUP = {4: 8, 3: 32, 2: 16}

HEAD = r"""; ----------------------------------------------------------------------------
; IMA-style ADPCM block decoder, 4, 3 or 2 bits (generated by gen_adpcm.py).
; One block, all channels, VIDC log bytes to r0 (the ring; stereo interleaved
; L,R). Per channel: int16 predictor, uint8 index, pad, then the codes as a
; little-endian bit stream (see adpcm_encode.py).
;
; Table driven: ima{B} has a word per (index, code) holding the signed
; difference << 13 and the next index's row offset, so one LDR does the step
; lookup, the adds, the sign and the index update. The 16-bit predictor
; indexes a 4 KB VIDC log table directly (12 bits).
;   r0 codes  r4 predictor  r5 &table  r6 current row  r7 dest
;   r8 count  r10 source  r11 &vidc12 centre  r12 0x7FFF

adpcm_decode_block:
	stmfd	sp!, {r4-r12, lr}
	mov	r7, r0
	ldr	r10, adp_next
	ldr	r11, p_vidc12
	mov	r12, #0x7F00
	orr	r12, r12, #0xFF
	ldr	r1, hdr_bs                 ; (kept on the stack: the loops are too
	str	r1, [sp, #-4]!             ;  long to reach hdr_bs PC-relative)
	ldr	r1, hdr_nch
	ldr	r0, adp_bits
	cmp	r0, #3
	beq	ad3
	blo	ad2
ad4:
	ldr	r5, p_ima4
	cmp	r1, #2
	beq	ad4_st
	b	ad4_mono
ad3:
	ldr	r5, p_ima3
	cmp	r1, #2
	beq	ad3_st
	b	ad3_mono
ad2:
	ldr	r5, p_ima2
	cmp	r1, #2
	beq	ad2_st
	b	ad2_mono
ad_done:
	add	sp, sp, #4
	str	r10, adp_next
	ldmfd	sp!, {r4-r12, pc}
p_ima4:	.long	ima4
p_ima3:	.long	ima3
p_ima2:	.long	ima2
"""

SAMPLE = """	add	r4, r4, r3, asr #13
	mov	r2, r4, asr #15            ; clamp to 16 bits
	teq	r2, r4, asr #31
	eorne	r4, r12, r4, asr #31
	mov	r3, r3, lsl #19
	add	r6, r5, r3, lsr #19
	ldrb	r1, [r11, r4, asr #4]
"""


def header(bits):
    return f"""	ldr	r1, [r10], #4
	mov	r4, r1, lsl #16
	mov	r4, r4, asr #16            ; predictor
	mov	r1, r1, lsr #16
	and	r1, r1, #0xFF              ; step index
	add	r6, r5, r1, lsl #{bits + 2}
	ldr	r8, [sp]
"""


def group(bits, stereo):
    """One unrolled group of codes."""
    out, word = [], -1
    mask = (1 << bits) - 1
    for k in range(GROUP[bits]):
        p = k * bits
        w, o = divmod(p, 32)
        if o + bits <= 32:
            if w != word:
                out.append("\tldr\tr0, [r10], #4")
                word = w
            out.append(f"\tand\tr1, r0, #0x{mask << o:X}")
            sh = f"lsr #{o - 2}" if o > 2 else ("lsl #%d" % (2 - o) if o < 2 else "")
            out.append(f"\tldr\tr3, [r6, r1{', ' + sh if sh else ''}]")
        else:                                   # straddles two words
            lo = 32 - o
            out.append(f"\tmov\tr1, r0, lsr #{o}")
            out.append("\tldr\tr0, [r10], #4")
            word = w + 1
            out.append(f"\tand\tr2, r0, #0x{(1 << (bits - lo)) - 1:X}")
            out.append(f"\torr\tr1, r1, r2, lsl #{lo}")
            out.append("\tldr\tr3, [r6, r1, lsl #2]")
        out.append(SAMPLE.rstrip("\n"))
        if stereo:
            out.append("\tstrb\tr1, [r7], #2")
        else:
            acc = "r9" if k % 8 < 4 else "lr"
            out.append(f"\tmov\t{acc}, r1" if k % 4 == 0 else f"\torr\t{acc}, {acc}, r1, lsl #{8 * (k % 4)}")
            if k % 8 == 7:
                out.append("\tstmia\tr7!, {r9, lr}")
    return "\n".join(out) + "\n"


def loops(bits):
    g = GROUP[bits]
    return (f"ad{bits}_mono:\n" + header(bits) + f"ad{bits}_m_loop:\n" + group(bits, False)
            + f"\tsubs\tr8, r8, #{g}\n\tbgt\tad{bits}_m_loop\n\tb\tad_done\n"
            + f"ad{bits}_st:\n\tmov\tlr, #2\nad{bits}_st_chan:\n" + header(bits)
            + f"ad{bits}_st_loop:\n" + group(bits, True)
            + f"\tsubs\tr8, r8, #{g}\n\tbgt\tad{bits}_st_loop\n"
            + "\tldr\tr0, [sp]\n\tsub\tr7, r7, r0, lsl #1\n\tadd\tr7, r7, #1          ; channel 2: odd bytes\n"
            + f"\tsubs\tlr, lr, #1\n\tbgt\tad{bits}_st_chan\n\tb\tad_done\n")


def table(bits):
    diff, nxt = ae.tables(bits)
    out = bytearray()
    for i in range(89):
        for c in range(1 << bits):
            out += struct.pack("<I", ((int(diff[i, c]) << 13) | (int(nxt[i, c]) << (bits + 2))) & 0xFFFFFFFF)
    return bytes(out)


def write(build):
    src = HEAD + "".join(loops(b) for b in (4, 3, 2))
    with open(os.path.join(build, "adpcm_dec.inc"), "w") as f:
        f.write(src)
    for b in (4, 3, 2):
        with open(os.path.join(build, f"ima{b}.bin"), "wb") as f:
            f.write(table(b))
